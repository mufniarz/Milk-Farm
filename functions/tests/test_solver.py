"""
Golden-data tests for the TMR solver (functions/solver.py).

Uses the fixture generated by scripts/parse-excel.cjs (reference_rations.json)
so the feed library, targets and expected analysis all trace back to the source
spreadsheet docs/ALIMENTAZIONE.xlsx. The same file is the single source of
truth for the workbook-parity test.
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(__file__)))  # functions/

from solver import solve_ration, _build_result  # noqa: E402

REFERENCE = json.load(
    open(os.path.join(os.path.dirname(__file__), "reference_rations.json"))
)["lactating"]

FIXTURE = {
    "feeds": REFERENCE["feeds"],
    "targets": REFERENCE["targets"],
    "goldenRation": REFERENCE["quantities"],
    "goldenAnalysis": REFERENCE["analysis"],
    "referenceCost": REFERENCE["costPerHead"],
    "referenceTotalDM": REFERENCE["solverTotalDM"],
}


def test_reference_ration_analysis_matches_spreadsheet():
    """Feeding the reference quantities reproduces the spreadsheet analysis."""
    feeds = FIXTURE["feeds"]
    quantities = {r["id"]: r["kgAsFed"] for r in FIXTURE["goldenRation"]}

    result = _build_result(feeds, quantities)
    analysis = result["nutrientAnalysis"]

    # The workbook rounds its published values to two decimals; 0.03 pp is the
    # observed maximum deviation of the computed ration from those values.
    for code, expected in FIXTURE["goldenAnalysis"].items():
        assert abs(analysis[code] - expected) <= 0.03, (
            code,
            analysis[code],
            expected,
        )

    # Commercial totals: exact to a tenth of a cent, and within 0.01 kg of the
    # workbook's Kg s.s. (the feed library rounds moisture to one decimal).
    assert abs(result["totalAsFed"] - REFERENCE["totalAsFed"]) <= 0.01
    assert abs(result["totalDM"] - REFERENCE["workbookTotalDM"]) <= 0.01
    assert abs(result["totalCost"] - FIXTURE["referenceCost"]) <= 0.001


def test_solver_respects_hard_constraints_and_minimizes_cost():
    """The LP finds an optimal ration honoring moisture + forage HARD bounds."""
    feeds = FIXTURE["feeds"]
    targets = [
        {"code": "proteina", "min": 14.5, "max": 16.5},
        {"code": "amido", "min": 22.0, "max": 28.0},
    ]
    constraints = {
        "totalDM": FIXTURE["referenceTotalDM"],
        "minMoisturePct": 50.0,
        "maxMoisturePct": 55.0,
        "minForageRatio": 0.40,
        "maxForageRatio": 0.45,
    }

    result = solve_ration(feeds, targets, constraints)

    assert result["status"] == "optimal", result.get("message")

    a = result["nutrientAnalysis"]
    assert 50.0 - 0.5 <= a["umidita"] <= 55.0 + 0.5
    assert 40.0 - 0.5 <= a["foraggiPct"] <= 45.0 + 0.5
    assert 14.5 - 0.1 <= a["proteina"] <= 16.5 + 0.1
    assert 22.0 - 0.1 <= a["amido"] <= 28.0 + 0.1

    # A cost-minimizing solution must not exceed the reference recipe cost.
    assert result["totalCost"] <= FIXTURE["referenceCost"] + 1e-6


def test_conflicting_targets_fall_back_to_relaxed():
    """Unsatisfiable derived targets should yield a relaxed (not error) result."""
    feeds = FIXTURE["feeds"]
    # ADF/aNDF target 60-65 is unreachable with this feed library (~49.5).
    targets = [{"code": "ADF_aNDF", "min": 60.0, "max": 65.0}]
    constraints = {"totalDM": FIXTURE["referenceTotalDM"]}

    result = solve_ration(feeds, targets, constraints)

    assert result["status"] in ("relaxed", "optimal")
    if result["status"] == "relaxed":
        assert any(w["code"] == "ADF_aNDF" for w in result.get("warnings", []))


def test_missing_total_dm_is_rejected():
    """A ration needs a fixed intake: without one the cheapest answer is 1 kg."""
    result = solve_ration(FIXTURE["feeds"], [], {})

    assert result["status"] == "error"
    assert "totalDM" in result["message"]


def _solver_targets():
    return [
        {
            "code": target["nutrientCode"],
            "min": target["minValue"],
            "max": target["maxValue"],
        }
        for target in FIXTURE["targets"]
        if target.get("isActive")
    ]


def test_strict_mode_rejects_relaxed_reference():
    """Strict mode must not silently soften unreachable targets."""
    result = solve_ration(
        FIXTURE["feeds"],
        _solver_targets(),
        {
            "totalDM": 23.1,
            "minMoisturePct": 50.0,
            "maxMoisturePct": 55.0,
            "minForageRatio": 0.40,
            "maxForageRatio": 0.45,
        },
        mode="strict",
    )
    assert result["status"] == "infeasible"
    assert "strict" in result["message"].lower()
    assert "ADF_aNDF" in {
        target["code"] for target in result["unreachableTargets"]
    }
    assert result["warnings"] == result["unreachableTargets"]


def test_strict_mode_reports_multiple_unreachable_targets():
    result = solve_ration(
        FIXTURE["feeds"],
        [
            {"code": "aNDF", "min": 70.0, "max": 75.0},
            {"code": "ADF", "min": 60.0, "max": 65.0},
        ],
        {"totalDM": 23.1},
        mode="strict",
    )
    assert result["status"] == "infeasible"
    codes = {target["code"] for target in result["unreachableTargets"]}
    assert {"aNDF", "ADF"}.issubset(codes)


def test_relaxed_reference_keeps_absolute_fibre_floors():
    """The relaxed solution may miss derived ratios, not the absolute floors."""
    result = solve_ration(
        FIXTURE["feeds"],
        _solver_targets(),
        {
            "totalDM": 23.1,
            "minMoisturePct": 50.0,
            "maxMoisturePct": 55.0,
            "minForageRatio": 0.40,
            "maxForageRatio": 0.45,
        },
        mode="relaxed",
    )
    assert result["status"] == "relaxed"
    analysis = result["nutrientAnalysis"]
    assert analysis["aNDF"] >= 28.0 - 0.1
    assert analysis["ADF"] >= 18.0 - 0.1
    assert analysis["uNDF"] >= 9.0 - 0.1
    warnings = {
        warning["code"]: warning for warning in result.get("warnings", [])
    }
    assert warnings["ADF_aNDF"]["issue"] == "below_min"
    assert warnings["ADF"]["issue"] == "at_boundary"
    assert warnings["uNDF_aNDF"]["issue"] == "at_boundary"
    assert "aNDF" not in warnings
    assert "uNDF" not in warnings
