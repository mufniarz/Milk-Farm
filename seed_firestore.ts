/**
 * Seed script: Populates Firestore from the Excel-derived initial data.
 *
 * Usage:
 *   npm run seed                                           # default: creates new farm + user
 *   npm run seed -- --farm-id my-farm                      # seed into existing farm (new user)
 *   npm run seed -- --farm-id my-farm --uid my-user        # seed into existing farm + user
 *
 * Requires: @google-cloud/firestore
 *
 * This script creates:
 * 1. A default farm + demo user (via Admin SDK — bypasses security rules)
 * 2. The /nutrients master collection (measured + derived definitions)
 * 3. The real feed library parsed from docs/ALIMENTAZIONE.xlsx
 * 4. Animal groups with their nutrient target ranges
 *
 * The data comes from src/app/core/data/initial-data.ts, which is generated by
 * scripts/parse-excel.cjs. Re-run that generator to refresh the source data.
 *
 * ── How to get a service account key ───────────────────────────────────────
 * 1. Go to Firebase Console → Project Settings → Service Accounts
 * 2. Click "Generate new private key" → downloads a JSON file
 * 3. Place it in the project root as `firebase-service-account.json`
 *    (this file is .gitignored — never commit it)
 * 4. Run this script — it will auto-detect the key.
 * ────────────────────────────────────────────────────────────────────────────
 */

import { Firestore, CollectionReference, DocumentReference } from '@google-cloud/firestore';
import * as fs from 'fs';
import * as path from 'path';

import {
  NUTRIENTS_MASTER,
  ANIMAL_GROUPS,
  FEEDS_SEED,
  TARGET_RANGES,
} from './src/app/core/data/initial-data';

// ── Initialize Firestore via Admin SDK ──────────────────────────────────────
const KEY_PATH = 'firebase-service-account.json';
const PROJECT_ID = 'nicola-milk-farm';

const keyFile = path.resolve(KEY_PATH);
let db: Firestore;

if (fs.existsSync(keyFile)) {
  const key = JSON.parse(fs.readFileSync(keyFile, 'utf8'));
  db = new Firestore({
    projectId: key.project_id,
    credentials: key,
  });
  console.log(`🔑 Loaded service account key: ${KEY_PATH}`);
} else {
  console.error(`\n❌ Service account key not found at ${KEY_PATH}`);
  console.error('Download it from Firebase Console → Project Settings → Service Accounts.');
  console.error('Place it in the project root as firebase-service-account.json\n');
  process.exit(1);
}

// ── CLI flag parsing ─────────────────────────────────────────────────────────
function parseArgs(argv: string[]): { farmId?: string; uid?: string } {
  const args: { farmId?: string; uid?: string } = {};
  for (let i = 2; i < argv.length; i++) {
    switch (argv[i]) {
      case '--farm-id':
      case '--farmId':
      case '--fid':
        args.farmId = argv[++i];
        break;
      case '--uid':
      case '--user-id':
        args.uid = argv[++i];
        break;
      default:
        console.warn(`⚠️  Unknown flag: ${argv[i]}`);
    }
  }
  return args;
}

const cli = parseArgs(process.argv);
const farmId = cli.farmId || 'seed-farm-' + Date.now();
const uid = cli.uid || 'seed-user-' + Date.now();

// ── Helpers ──────────────────────────────────────────────────────────────────
async function setDoc(ref: DocumentReference, data: any): Promise<void> {
  await ref.set(data);
}

async function seed(): Promise<void> {
  console.log('🌱 Seeding Firestore from Excel-derived data...\n');

  // ── Nutrient master collection ──
  const nutrientsRef = db.collection('nutrients');
  for (const n of NUTRIENTS_MASTER) {
    await setDoc(nutrientsRef.doc(n.code), n);
  }
  console.log(`✅ Nutrients master: ${NUTRIENTS_MASTER.length} definitions`);

  // ── Farm + demo user ──
  const farmProvided = cli.farmId !== undefined;
  const uidProvided = cli.uid !== undefined;

  await setDoc(db.collection('farms').doc(farmId), {
    id: farmId,
    name: farmProvided ? 'Seeded Farm' : 'Demo Farm (Seed Data)',
    ownerUid: uid,
    createdAt: new Date(),
  });
  console.log(`✅ Farm: ${farmId}${farmProvided ? ' (existing)' : ' (created)'}`);

  await setDoc(db.collection('users').doc(uid), {
    uid,
    displayName: 'Demo User',
    email: 'demo@milkfarm.local',
    farmId,
    language: 'it',
    createdAt: new Date(),
  });
  console.log(`✅ User: ${uid}${uidProvided ? ' (existing)' : ' (created)'}`);

  // ── Feeds ──
  const feedsRef = db.collection('feeds');
  for (const feed of FEEDS_SEED) {
    const docRef = feedsRef.doc();
    await setDoc(docRef, {
      ...feed,
      farmId,
      updatedAt: new Date(),
    });
  }
  console.log(`✅ Created ${FEEDS_SEED.length} feeds`);

  // ── Animal groups + targets ──
  const groupsRef = db.collection('animalGroups');
  for (const group of ANIMAL_GROUPS) {
    await setDoc(groupsRef.doc(group.id), group);

    const targets = TARGET_RANGES[group.id] ?? [];
    const targetsRef = db.collection('animalGroups').doc(group.id).collection('targets');
    for (const target of targets) {
      await setDoc(targetsRef.doc(target.nutrientCode), target);
    }
    console.log(
      `  ✅ Animal group: ${group.nameIt} (${group.id}) — ${targets.length} targets`,
    );
  }

  console.log('\n✅ Seed complete!');
  console.log(`   Farm: ${farmId}`);
  console.log(`   User: ${uid}`);
  console.log(
    `\nNote: create a Firebase Auth user (via the console) with UID="${uid}" to log in against this farm.\n`,
  );
}

seed().catch((err) => {
  console.error('❌ Seed failed:', err);
  process.exit(1);
});
